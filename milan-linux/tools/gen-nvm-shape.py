"""gen-nvm-shape.py - nvm_shape_gen.h for the saved-state store on Linux (#13).

The Mark II store (milan-fpga sw/firmware/ctrl_nvm) is compiled against the
shape constants of one end-station config: its record set, its binding layout
and the journal's place. milan-fpga's own host suite derives them
(sw/firmware/ctrl_nvm/test/nvm_bench.py shape_header), and this runs that
derivation, never a restated copy.

Its inputs are what nvm_bench.shape_inputs reads after a builder run
(scripts/nvm_shape.py build): the config's AEM overlay, its record space
(nvm_split.json) and the image's writable-name count. The builder's build()
refuses a descriptor-only host profile (it writes no gateware), so the same
two documents come from the builder's own emitters (emit_aem_overlay,
emit_nvm_split), which build() writes them from, and the name count from the
same image generator nvm_shape.build runs (avdecc/gen_aemi_image.py).

One change: on the PocketBeagle 2 the entity ID is known only at run time (it
is eth0's MAC, expanded), so the four identity words become variables
milan-ctrld sets before the store boots. The model ID the shape was derived
for stays a constant, MILAN_NVM_SHAPE_MODEL_ID_LO/HI, which milan-ctrld
checks against the entity it advertises.

usage: gen-nvm-shape.py <milan-fpga tree> <end-station yaml> > nvm_shape_gen.h
"""

import json
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path


def shape_inputs(tree: Path, cfg: Path, work: Path):
    """nvm_bench.ShapeInputs for cfg, from the builder's emitters."""
    sys.path.insert(0, str(tree / "sw/builder"))
    sys.path.insert(0, str(tree / "sw/firmware/ctrl_nvm/test"))
    import endstation_builder as eb  # noqa: E402
    import nvm_bench as nb  # noqa: E402
    loaded = eb.load_config(str(cfg))
    overlay = eb.emit_aem_overlay(loaded)
    space = eb.emit_nvm_split(overlay)
    ovl = work / "aem_overlay.json"
    ovl.write_text(json.dumps(overlay, indent=1) + "\n")
    img = work / "aem.img.bin"
    subprocess.run([sys.executable, str(tree / "avdecc/gen_aemi_image.py"), "--overlay", str(ovl), "-o", str(img),
                    "--line-bytes", "576"], check=True, cwd=tree, stdout=subprocess.DEVNULL)
    _, names = struct.unpack_from(">HH", img.read_bytes(), 8)
    ports = overlay["stream_ports"]
    ident = nb.Ident(seq=0, entity_id=int(overlay["adp"]["entity_id"], 16),
                     model_id=int(overlay["entity"]["entity_model_id"], 16))
    shape = nb.Shape(cfg=cfg, names=names, dc=overlay["descriptor_counts"], spi=ports["input"],
                     spo=ports["output"])
    return nb, nb.ShapeInputs(cfg=cfg, shape=shape, space=space, ident=ident, clock_hz=0)


def main() -> int:
    tree, cfg = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    with tempfile.TemporaryDirectory() as work:
        nb, inputs = shape_inputs(tree, cfg, Path(work))
        header = nb.shape_header(inputs)
    model = inputs.ident.model_id
    rev = (tree / ".milan-fpga-rev").read_text().strip() if (tree / ".milan-fpga-rev").exists() else "unknown"
    out = [f"/* GENERATED by milan-linux/tools/gen-nvm-shape.py from {cfg.name} at milan-fpga {rev},",
           " * through sw/firmware/ctrl_nvm/test/nvm_bench.py shape_header. DO NOT EDIT: regenerate.",
           " * The identity words are milan-ctrld's run-time variables (src/nvm_file.c). */"]
    for line in header.splitlines():
        if line.startswith("/*"):
            continue
        if re.match(r"#define (MILAN_(?:ENTITY|MODEL)_ID_(?:LO|HI)) ", line):
            continue
        out.append(line)
        if line == "#define NVM_SHAPE_GEN_H":
            out += ["#include <stdint.h>",
                    "extern uint32_t milan_nvm_entity_id_lo, milan_nvm_entity_id_hi;",
                    "extern uint32_t milan_nvm_model_id_lo, milan_nvm_model_id_hi;",
                    "#define MILAN_ENTITY_ID_LO milan_nvm_entity_id_lo",
                    "#define MILAN_ENTITY_ID_HI milan_nvm_entity_id_hi",
                    "#define MILAN_MODEL_ID_LO milan_nvm_model_id_lo",
                    "#define MILAN_MODEL_ID_HI milan_nvm_model_id_hi",
                    f"#define MILAN_NVM_SHAPE_MODEL_ID_LO 0x{model & 0xFFFF_FFFF:x}u",
                    f"#define MILAN_NVM_SHAPE_MODEL_ID_HI 0x{model >> 32:x}u"]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
